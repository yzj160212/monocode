/**
 * Generates the runtime translator injected into every HTML entry point.
 *
 * Why a runtime pass instead of rewriting sources: MonoCode is a dense React
 * app where the same literal is often both UI copy and a logic token (enum
 * comparisons, request headers, storage keys). Replacing a text node or a UI
 * attribute at the DOM level is provably safe, and it keeps the upstream tree
 * untouched so `git pull` never conflicts.
 *
 * Two things are translated here:
 *   - exact strings: a text node / attribute equals a dictionary key
 *   - patterns: a text node matches `Open {0}` style templates, with the
 *     interpolated part kept verbatim
 */

/** @param {{entries: Record<string,string>, patterns?: Record<string,string>}} payload */
export function renderRuntimeScript(payload, { hash = "dev" } = {}) {
  const entries = JSON.stringify(payload.entries ?? {});
  const patterns = JSON.stringify(payload.patterns ?? {});
  return `/* MonoCode 简体中文语言层 (${hash}) — generated by tools/zh-cn, do not edit. */
(function () {
  "use strict";

  var EXACT = ${entries};
  var PATTERN = ${patterns};
  var ATTRS = [
    "title", "placeholder", "aria-label", "aria-description", "alt", "summary",
  ];
  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, CODE: 1, PRE: 1, KBD: 1, TEXTAREA: 1 };

  // Compile patterns once: "Open {0}" -> /^Open (.*)$/
  var compiled = [];
  for (var key in PATTERN) {
    var parts = key.split(/\\{(\\d+)\\}/);
    var source = "";
    for (var i = 0; i < parts.length; i += 1) {
      if (i % 2 === 0) {
        source += parts[i].replace(/[.*+?^{}()|[\\]\\\\$]/g, "\\\\$&");
      } else {
        source += "([\\\\s\\\\S]*?)";
      }
    }
    compiled.push({ re: new RegExp("^" + source + "$"), out: PATTERN[key] });
  }

  function trimParts(value) {
    var lead = value.match(/^\\s*/)[0];
    var trail = value.match(/\\s*$/)[0];
    return [lead, value.slice(lead.length, value.length - (trail.length || 0)), trail];
  }

  function translate(value) {
    if (typeof value !== "string" || value.length === 0) return null;
    var parts = trimParts(value);
    var core = parts[1];
    if (!core) return null;
    var hit = EXACT[core];
    if (hit !== undefined && hit !== core) return parts[0] + hit + parts[2];
    for (var i = 0; i < compiled.length; i += 1) {
      var match = compiled[i].re.exec(core);
      if (!match) continue;
      var out = compiled[i].out;
      var body = out.replace(/\\{(\\d+)\\}/g, function (_, n) { return match[Number(n) + 1]; });
      return parts[0] + body + parts[2];
    }
    return null;
  }

  function skip(node) {
    var el = node.nodeType === 1 ? node : node.parentElement;
    while (el) {
      if (SKIP_TAGS[el.tagName]) return true;
      if (el.getAttribute("translate") === "no") return true;
      if (el.classList && (el.classList.contains("mono-user-input") || el.classList.contains("cm-content"))) return true;
      el = el.parentElement;
    }
    return false;
  }

  function textNode(node) {
    if (!node || node.nodeType !== 3) return;
    if (skip(node)) return;
    var next = translate(node.nodeValue);
    if (next !== null) node.nodeValue = next;
  }

  function attrs(el) {
    for (var i = 0; i < ATTRS.length; i += 1) {
      var attr = ATTRS[i];
      var current = el.getAttribute(attr);
      if (!current) continue;
      var next = translate(current);
      if (next !== null) el.setAttribute(attr, next);
    }
  }

  function element(el) {
    if (!el || el.nodeType !== 1) return;
    if (el.tagName === "INPUT" && (el.type === "button" || el.type === "submit")) {
      var value = el.getAttribute("value");
      var next = value && translate(value);
      if (next) el.setAttribute("value", next);
    }
    attrs(el);
  }

  function walk(root) {
    if (!root) return;
    if (root.nodeType === 3) {
      textNode(root);
      return;
    }
    if (root.nodeType === 9) {
      walk(root.body || root.documentElement);
      return;
    }
    if (root.nodeType !== 1 && root.nodeType !== 11) return;
    if (root.nodeType === 1) element(root);
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    var node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === 3) textNode(node);
      else element(node);
    }
  }

  // Keep our own writes from re-entering the observer.
  var writing = false;
  function observe() {
    if (typeof MutationObserver !== "function") return;
    var observer = new MutationObserver(function (records) {
      if (writing) return;
      writing = true;
      try {
        for (var i = 0; i < records.length; i += 1) {
          var record = records[i];
          if (record.type === "characterData") textNode(record.target);
          else if (record.type === "attributes") element(record.target);
          else if (record.type === "childList") {
            for (var j = 0; j < record.addedNodes.length; j += 1) walk(record.addedNodes[j]);
          }
        }
      } finally {
        writing = false;
      }
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTRS,
    });
  }

  function start() {
    document.documentElement.lang = "zh-CN";
    walk(document);
    // React mounts and re-renders constantly; observe after the first paint so
    // the initial pass is not split across thousands of mutation records.
    observe();
    var timer = setInterval(function () {
      if (!document.getElementById("root")) return;
      clearInterval(timer);
      walk(document);
    }, 400);
    setTimeout(function () { clearInterval(timer); }, 8000);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start, { once: true });
  } else {
    start();
  }
})();
`;
}
