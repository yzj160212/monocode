/**
 * Generates the Rust side of the Chinese layer and hooks it into the app.
 *
 * The native macOS menu is built in `src-tauri/src/menu.rs` from English
 * literals, and macOS itself draws some items (Undo, Cut, Hide Others, ...).
 * Rewriting those sources would conflict with upstream on every sync, so this
 * module instead:
 *
 *   1. writes `src-tauri/src/zh_cn.rs` with the id -> Chinese and
 *      English -> Chinese tables,
 *   2. inserts two lines into `src-tauri/src/lib.rs` (idempotent),
 *   3. localizes the Finder permission prompts in `src-tauri/Info.plist`.
 *
 * Everything is regenerated per build and never committed.
 */
import fs from "node:fs";
import path from "node:path";

const MOD_LINE = "mod zh_cn;";
const INSTALL_LINE = "            zh_cn::install(app.handle());";

function rustString(value) {
  return JSON.stringify(value);
}

function table(entries) {
  return entries.map(([key, value]) => `    (${rustString(key)}, ${rustString(value)}),`).join("\n");
}

/**
 * @param {string} root repository root
 * @param {{menu: {byId: Record<string,string>, byText: Record<string,string>,
 *          dockMenu?: Record<string,string>}, plist?: Record<string,string>}} data
 */
export function writeNativeModule(root, data) {
  const srcDir = path.join(root, "src-tauri", "src");
  const target = path.join(srcDir, "zh_cn.rs");
  const byId = Object.entries(data.menu?.byId ?? {}).sort(([a], [b]) => a.localeCompare(b));
  const byText = Object.entries(data.menu?.byText ?? {}).sort(([a], [b]) => a.localeCompare(b));
  const dock = Object.entries(data.menu?.dockMenu ?? data.menu?.byText ?? {}).sort(([a], [b]) => a.localeCompare(b));

  const source = `// 简体中文语言层：原生菜单本地化。
// Generated by tools/zh-cn/patch-native.mjs from the resolved zh-CN dictionary; do not edit.
//
// The webview is localized at runtime by zh-cn.js. Native AppKit menus cannot
// be reached from the webview, so they are retitled here after menu::install.
// Item ids are stable in menu.rs; macOS-drawn items (Undo, Hide Others, ...)
// and submenu captions are matched by their current text instead.

use tauri::menu::MenuItemKind;
use tauri::AppHandle;

/// Menu items created with an explicit id in menu.rs.
const BY_ID: &[(&str, &str)] = &[
${table(byId)}
];

/// Submenu captions and AppKit-drawn items, matched by current English text.
const BY_TEXT: &[(&str, &str)] = &[
${table(byText)}
];

/// The Dock context menu, which is built directly with AppKit.
const DOCK: &[(&str, &str)] = &[
${table(dock)}
];

fn lookup<'a>(table: &'a [(&'a str, &'a str)], text: &str) -> Option<&'a str> {
    let normalized = text.trim();
    // macOS strips mnemonics itself, but muda keeps them in the stored text.
    let plain = normalized.replace('&', "");
    table
        .iter()
        .find(|(english, _)| *english == normalized || *english == plain)
        .map(|(_, zh)| *zh)
}

#[cfg(target_os = "macos")]
fn retitle(item: &MenuItemKind<tauri::Wry>) {
    match item {
        MenuItemKind::Submenu(submenu) => {
            if let Ok(text) = submenu.text() {
                if let Some(zh) = lookup(BY_TEXT, &text) {
                    let _ = submenu.set_text(zh);
                }
            }
            if let Ok(children) = submenu.items() {
                for child in &children {
                    retitle(child);
                }
            }
        }
        MenuItemKind::MenuItem(item) => {
            if let Ok(text) = item.text() {
                let zh = lookup(BY_ID, item.id().as_ref())
                    .or_else(|| lookup(BY_TEXT, &text));
                if let Some(zh) = zh {
                    let _ = item.set_text(zh);
                }
            }
        }
        MenuItemKind::Check(item) => {
            if let Ok(text) = item.text() {
                let zh = lookup(BY_ID, item.id().as_ref())
                    .or_else(|| lookup(BY_TEXT, &text));
                if let Some(zh) = zh {
                    let _ = item.set_text(zh);
                }
            }
        }
        MenuItemKind::Icon(item) => {
            if let Ok(text) = item.text() {
                let zh = lookup(BY_ID, item.id().as_ref())
                    .or_else(|| lookup(BY_TEXT, &text));
                if let Some(zh) = zh {
                    let _ = item.set_text(zh);
                }
            }
        }
        MenuItemKind::Predefined(item) => {
            if let Ok(text) = item.text() {
                if let Some(zh) = lookup(BY_TEXT, &text) {
                    let _ = item.set_text(zh);
                }
            }
        }
    }
}

#[cfg(target_os = "macos")]
fn localize_dock_menu() {
    use objc2::sel;
    use objc2_app_kit::{NSApplication, NSMenu};
    use objc2_foundation::MainThreadMarker;

    let Some(mtm) = MainThreadMarker::new() else {
        return;
    };
    let app = NSApplication::sharedApplication(mtm);
    // dockMenu is only reachable through the deprecated selector, and sending
    // an unimplemented selector aborts the process (objc2 cannot unwind an
    // NSException). Probe first; a nil menu simply means there is nothing to do.
    let responds: bool = unsafe { objc2::msg_send![&*app, respondsToSelector: sel!(dockMenu)] };
    if !responds {
        return;
    }
    let menu: Option<objc2::rc::Retained<NSMenu>> = unsafe { objc2::msg_send![&*app, dockMenu] };
    let Some(menu) = menu else {
        return;
    };
    for item in menu.itemArray().iter() {
        let title = item.title().to_string();
        if let Some(zh) = lookup(DOCK, &title) {
            item.setTitle(&objc2_foundation::NSString::from_str(zh));
        }
    }
}

/// Retitles the macOS menu bar after menu::install or a keybinding rebuild.
///
/// MonoCode rebuilds the whole menu from English literals when the frontend
/// pushes keybinding overrides, so this has to run after every set_menu, not
/// just once at startup.
pub fn localize(app: &AppHandle) {
    #[cfg(target_os = "macos")]
    {
        if let Some(menu) = app.menu() {
            if let Ok(items) = menu.items() {
                for item in &items {
                    retitle(item);
                }
            }
        }
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = app;
    }
}

/// Retitles the macOS menu bar and Dock menu. No-op on other platforms.
pub fn install(app: &AppHandle) {
    #[cfg(target_os = "macos")]
    {
        localize(app);
        localize_dock_menu();
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = app;
    }
}
`;
  fs.writeFileSync(target, source);
  return target;
}

/** Inserts the module + install hook into lib.rs. Returns true when changed. */
export function hookLibRs(root) {
  const libRs = path.join(root, "src-tauri", "src", "lib.rs");
  let code = fs.readFileSync(libRs, "utf8");
  if (/^mod zh_cn;$/m.test(code) && code.includes("zh_cn::install(app.handle());")) {
    return false;
  }
  const lines = code.split("\n");
  if (!/^mod zh_cn;$/m.test(code)) {
    const anchor = lines.findIndex((line) => line.trim() === "mod menu;");
    if (anchor === -1) throw new Error("lib.rs: cannot find `mod menu;` anchor");
    lines.splice(anchor + 1, 0, MOD_LINE);
  }
  // Must run after the Dock menu exists, so anchor on the last menu step.
  let installAnchor = lines.findIndex((line) => line.includes("macos::install_dock_menu(app.handle())"));
  if (installAnchor === -1) {
    installAnchor = lines.findIndex((line) => line.includes("menu::install(app.handle())"));
  }
  if (installAnchor === -1) throw new Error("lib.rs: cannot find a menu install anchor");
  const indent = lines[installAnchor].match(/^\s*/)[0];
  lines.splice(installAnchor + 1, 0, `${indent}zh_cn::install(app.handle());`);
  code = lines.join("\n");
  fs.writeFileSync(libRs, code);
  return true;
}

/**
 * Re-localizes the menu after `menu::keybindings_set_overrides` rebuilds it.
 *
 * The frontend pushes saved keybindings on mount and on every settings edit;
 * that command replaces the whole menu with English literals. Retitling right
 * after the swap keeps the bar Chinese without touching menu.rs semantics.
 */
export function hookMenuRs(root) {
  const file = path.join(root, "src-tauri", "src", "menu.rs");
  let code = fs.readFileSync(file, "utf8");
  if (code.includes("crate::zh_cn::localize")) return false;
  const anchor = "    app.set_menu(menu)\n        .map(|_| ())";
  if (!code.includes(anchor)) {
    throw new Error("menu.rs: cannot find the set_menu call in keybindings_set_overrides");
  }
  code = code.replace(
    anchor,
    "    let applied = app.set_menu(menu);\n    crate::zh_cn::localize(&app);\n    applied\n        .map(|_| ())",
  );
  fs.writeFileSync(file, code);
  return true;
}

/**
 * Writes a localized copy of the Finder permission prompts.
 *
 * The upstream `Info.plist` is never modified: the override config points
 * `bundle.macOS.infoPlist` at this file, and Tauri merges it into the bundle.
 */
export function writeLocalizedPlist(root, plist) {
  if (!plist || Object.keys(plist).length === 0) return null;
  const source = path.join(root, "src-tauri", "Info.plist");
  if (!fs.existsSync(source)) return null;
  let xml = fs.readFileSync(source, "utf8");
  let changed = false;
  for (const [key, zh] of Object.entries(plist)) {
    const escaped = zh.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    const re = new RegExp(`(<key>${key}</key>\\s*<string>)([^<]*)</string>`);
    if (!re.test(xml)) continue;
    const next = xml.replace(re, `$1${escaped}</string>`);
    if (next !== xml) {
      xml = next;
      changed = true;
    }
  }
  if (!changed) return null;
  const target = path.join(root, "src-tauri", "Info.zh.plist");
  fs.writeFileSync(target, xml);
  return target;
}

export { INSTALL_LINE, MOD_LINE };
